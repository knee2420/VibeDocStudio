// <<document:hwp>> 수요조사 원문을 복제하되, WebForm은 문서 크기로 페이지를 자르지 않도록 <<page>> 경계 없이 연속 단일 폼으로 구성한다.
const wsDocsSection = WORKSHOP_REQUEST_SPEC.nodes.find((n) => n.id === "ws-sec-documents");
const wsRawSurveyNode = wsDocsSection?.children.find((n) => n.id === "ws-doc-survey-raw");
if (wsDocsSection && wsRawSurveyNode) {
  const flattenAsWebForm = (node: PlaygroundNode): PlaygroundNode[] => {
    const remappedId =
      node.id === "ws-doc-survey-raw"
        ? "ws-doc-survey-web"
        : node.id.replace("ws-doc-raw", "ws-doc-web");
    // <<view:...>> 컴파일된 HWP 표 뷰 노드는 WebForm 원문 복제에서 제외한다.
    if (/<<\s*view(?::[^>]+)?\s*>>/i.test(node.text)) {
      return [];
    }
    // HWP의 <<page:...>> 래퍼는 WebForm에서 페이지 절단 없이 하위 섹션들을 그대로 이어 붙인다.
    if (/<<page(?::[^>]+)?>>/i.test(node.text)) {
      return node.children.flatMap(flattenAsWebForm);
    }
    const cleanText = node.text
      .replace("2쪽 스키장 낮 활동", "낮 활동 설문 구성")
      .replace("3쪽 저녁 만찬 · 비음주 레크", "저녁 만찬 · 레크 설문 구성");
    return [
      {
        ...node,
        id: remappedId,
        text: cleanText,
        children: node.children.flatMap(flattenAsWebForm),
      },
    ];
  };

  const webRoot: PlaygroundNode = {
    ...wsRawSurveyNode,
    id: "ws-doc-survey-web",
    text: "스키장의 일정 및 활동 1차 수요조사 <<document:WebForm>>",
    note: "웹 설문(연속 스크롤) · 페이지 분할 없음 · UI 테마 선택 가능",
    isFolded: true,
    children: wsRawSurveyNode.children.flatMap(flattenAsWebForm),
  };
  wsDocsSection.children.splice(1, 0, webRoot);
}

